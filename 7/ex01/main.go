// Package main предоставляет функции для вычисления набора монет, которыми
// можно выразить заданную сумму: мин. кол-во монет.
// В отличие от жадного алгоритма (minCoins), функция minCoins2 использует
// динамическое программирование, что гарантирует нахождение оптимального решения
// при любых наборах монет (в том числе неканонических).
package ex00

import (
	"sort"
)

// MinCoins2 корректно находит набор монет,
// даже при наличии дубликатов и неотсортированного массива.
// Если массив монет пуст - возвращает пустой результат.
//
// Алгоритм (динамическое программирование):
//  1. Удаляем дубли и сортируем (для удобства восстановления).
//  2. Создаём dp-массив размером val+1: dp[i] = минимальное кол-во монет для суммы i.
//  3. Изначально dp[0] = 0, dp[i] = +∞ для i>0 (но в Go это может быть большая константа).
//  4. По всем i (от 1 до val) и по всем монетам c обновляем dp[i] = min(dp[i], dp[i-c] + 1) если i-c>=0.
//  5. Чтобы потом восстановить набор монет, можно хранить вспомогательный массив choice[i],
//     в котором лежит монета, которая привела к оптимальному dp[i].
//  6. По массиву choice восстанавливаем конечный набор монет.
func MinCoins2(val int, coins []int) []int {
	if val <= 0 || len(coins) == 0 {
		// Если нужно набрать 0 или монет нет - возвращаем пустой набор
		return nil
	}

	// Удалим дубли, отсортируем
	uniqueCoins := make(map[int]bool)
	for _, c := range coins {
		uniqueCoins[c] = true
	}
	var sortedCoins []int
	for c := range uniqueCoins {
		sortedCoins = append(sortedCoins, c)
	}
	sort.Ints(sortedCoins)

	// Создаём dp-массив
	// dp[i] = минимальное число монет для i
	// choice[i] = какая последняя монета была выбрана, чтобы получить dp[i]
	dp := make([]int, val+1)
	choice := make([]int, val+1)
	const INF = 1_000_000_000

	for i := 1; i <= val; i++ {
		dp[i] = INF
		choice[i] = -1
	}

	dp[0] = 0 // 0 монет для суммы 0

	for i := 1; i <= val; i++ {
		for _, c := range sortedCoins {
			if c <= i && dp[i-c] != INF && dp[i-c]+1 < dp[i] {
				dp[i] = dp[i-c] + 1
				choice[i] = c
			}
		}
	}

	// Если dp[val] так и осталось INF, значит собрать сумму val не можем
	if dp[val] == INF {
		return nil
	}

	// Восстанавливаем набор монет из choice
	var res []int
	cur := val
	for cur > 0 {
		c := choice[cur]
		if c == -1 {
			// Такое в принципе уже не должно случиться, но на всякий случай
			break
		}
		res = append(res, c)
		cur -= c
	}

	return res
}
